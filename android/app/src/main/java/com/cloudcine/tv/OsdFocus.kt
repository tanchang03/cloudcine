package com.cloudcine.tv

/**
 * 播放页 OSD（菜单）的**光标判据** —— 纯函数，可在 JVM 单测里钉死。
 *
 * ## 为什么要有这个文件
 *
 * OSD 分两层：左侧**导航栏**（选哪一行）与右侧**选项区**（改这一行的值）。
 * 右侧有两种形态，而它们对「光标在左栏时 ←→ 有没有用」的回答**不一样**：
 *
 * | 形态 | 光标在左栏时 ←→ | 右侧那一项是光标吗 |
 * |---|---|---|
 * | 横向 chips（画质 / 连接数 / 倍速 / 字幕…） | **能**直接改值 | 是 |
 * | 纵向列表（选集） | **没有任何作用**，要按 →/OK 进入列表 | 不是 |
 *
 * 于是「纵向列表里选中那一项」在没进列表时画光标态是**假的**：
 * 用户看到一块品牌色实心，以为焦点在那里，按 ↑↓ 却是在挪左栏。
 *
 * 2026-10-11 用户反馈：
 * > 「菜单页中也有相同的焦点冲突问题，默认菜单打开后，看起来焦点在
 * > 选集列表，但是实际上在导航菜单」
 *
 * 不变量与 `LibraryActivity` 那边一致：**同一时刻只有一层在发光**。
 */
object OsdFocus {

    /**
     * 右侧**纵向列表**里第 [position] 项现在该不该画「光标态」。
     *
     * ⛔ 没进列表（[inList] = false）时**一律不画** —— 那时光标在左栏，
     *    ←→ 对列表没有任何作用，画出来就是在骗用户。
     *
     * ⛔ 但那一项仍然保留「**正在播的那一集**」的状态标记（`▶ ` 前缀 +
     *    左侧品牌色竖条，见 `TvOsdView.RowListAdapter`）。那是**事实**而不是
     *    光标，两者不能混为一谈：
     *      * 状态标记要**一直在**（哪怕光标在左栏，用户也得知道现在放的是哪集）；
     *      * 光标态必须**跟着输入走**（进了列表才亮，退出就收）。
     *
     * ⛔ 与横向 chips 的差别是本判据存在的全部理由：chips 那一行，光标在左栏
     *    时 ←→ 就能直接改值，所以 chip 上的 ACCENT 是**真光标**，
     *    不适用这一条（见 `TvOsdView.chipBackground`）。
     */
    fun listItemIsCursor(position: Int, cursor: Int, inList: Boolean): Boolean =
        inList && position == cursor

    // ------------------------------------------------------------------
    // 光标的可见性（纵向列表怎么滚）
    // ------------------------------------------------------------------

    /** 光标挪动之后，纵向列表**该不该滚、往哪滚**。 */
    enum class ListScroll {
        /** 光标还在可视区里 ⇒ **一点都不用滚**，只重画（高亮自己会走）。 */
        KEEP,

        /** 光标跑到可视区**上方** ⇒ 把它滚到第一行。 */
        TO_TOP,

        /** 光标跑到可视区**下方** ⇒ 把它滚到底行。 */
        TO_BOTTOM,
    }

    /**
     * 光标挪到 [cursor] 之后，列表要怎么滚才既跟得上、又**不整体平移**。
     *
     * ## 为什么不能直接 `ListView.setSelection(cursor)`
     *
     * `setSelection(pos)` 的语义是「把 pos 滚到**第一行**」
     * （= `setSelectionFromTop(pos, 0)`）。于是 ↑↓ 每挪一格，内容就整体滚一格，
     * 而高亮框**一直钉在第一行** —— 用户看到的是「数据在滚、焦点没动」。
     * 2026-10-11 用户反馈的原话：
     *
     * > 「默认选中第 1 集，点击遥控器下按钮，选中第 2 集，结果焦点依然是在
     * > 第一行，看起来并没有感觉是焦点在动，而是数据在滚动」
     *
     * 正确的手感是**边界才滚**：
     *
     * ```
     * 光标在可视区里  → 高亮自己往下走，内容不动
     * 撞到下边界      → 光标留在底行，内容往上滚一行
     * 撞到上边界      → 光标留在首行，内容往下滚一行
     * ```
     *
     * 这与 Android TV 自带设置页的手感一致。
     *
     * ⛔ 别改成 `smoothScrollToPosition`：OSD 的整套取舍是「一帧到位、
     *    不做动画」（见 `TvOsdView` 类注释），动画会让「按键→上屏」
     *    多出一段无谓的时间。
     */
    fun listScrollFor(cursor: Int, firstVisible: Int, lastVisible: Int): ListScroll = when {
        cursor < firstVisible -> ListScroll.TO_TOP
        cursor > lastVisible -> ListScroll.TO_BOTTOM
        else -> ListScroll.KEEP
    }
}
