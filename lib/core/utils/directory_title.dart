/// 目录名 → 作品名（系列名）—— **判定单元是目录，不是文件**。
///
/// ## 为什么需要它
///
/// 2026-10-02 事故：`/来自：分享/姜松《家电维修视频教程》/182.格力空调显示E6如何维修.mp4`
/// 被当成一部独立作品，标题是文件名里截出来的「182 格力空调显示」，
/// 然后被刮成了希腊纪录片《1821: Οι Ήρωες》。
///
/// 那个目录里还有 221 个同形文件（`1.家电维修学习介绍.mp4`、
/// `2.2交流电的概念.mp4`…），它们本该是**同一部教程的 222 集**。
///
/// ## 为什么单看一个文件名判不出来
///
///   - `/姜松《家电维修视频教程》/182.格力空调显示E6如何维修.mp4`  → 目录名才是系列名
///   - `/我的电影/01.流浪地球2.mp4`                              → 目录名是片单名，不是系列名
///
/// **这两者的文件名形态一模一样。** 唯一的区别是同目录其他文件长什么样。
/// 所以判据必须建立在目录这一级上。
///
/// ## 为什么「末级目录名」还不够 —— 必须向上回溯
///
/// 实测用户网盘 2847 个视频：**118 个目录（1291 个视频）** 的末级目录名是
/// 容器名，几乎全部来自 `尚硅谷嵌入式全套教程`：
///
///   `/…/01_尚硅谷嵌入式技术之C语言/4.视频/day01/`   ← 名字在上两级
///   `/…/10_尚硅谷嵌入式项目之畜牧牛羊定位器/04_视频/`
///
/// 只取末级会得到 118 个叫「day01」「04_视频」的作品。所以规则是
/// **从末级往上找，第一个像名字的那一级**。
///
/// ## 分工
///
/// 这里只回答「目录名像不像一个作品名」。**这个目录到底是不是
/// 「一集一个文件」的容器**由调用方判断（见 `MediaFilenameParser`：
/// 文件名自带年份/季集时它自己就说得清楚，轮不到目录名）。
library;

/// 归一化：只留小写字母数字与汉字。
///
/// 与 `scrape_match.dart` / `MediaCategoryGuesser` 的口径一致 ——
/// 三处对「什么算同一个名字」的理解一旦不同，就会出现
/// 「目录名判成了系列、刮削又当成另一部片」这种极难排查的不一致。
String _norm(String s) =>
    s.toLowerCase().replaceAll(RegExp(r'[^a-z0-9\u4e00-\u9fff]'), '');

/// 目录名 → 作品名。
abstract final class DirectoryTitle {
  const DirectoryTitle._();

  /// 容器名 —— **整段精确匹配**（归一化后），不做子串匹配。
  ///
  /// 为什么必须精确：`姜松家电维修合集`、`电影天堂经典合集` 里都含「合集」，
  /// 但它们是名字不是容器。按子串判会把它们一起吃掉。
  static const List<String> _containerWords = [
    // 分享路径噪音（用户的每一层都在 `来自：分享` 底下）
    '来自分享', '我的分享', '分享', '转存', '保存到我的网盘', '百度网盘', '阿里云盘',
    // 整理态
    '新建文件夹', '未命名文件夹', '未命名', '副本', '未分类', '未整理', '待整理',
    '待分类', '其他', '其它', '下载', '我的资源', '我的视频', '我的电影', '资源',
    '合集', '收藏', '经典', '已整理', '临时', 'temp',
    // 栏目名
    '电影', '电视剧', '剧集', '美剧', '日剧', '韩剧', '港剧', '台剧', '国产剧',
    '欧美剧', '动漫', '动画', '番剧', '新番', '国漫', '日漫', '综艺', '纪录片',
    '纪实', '短片', '微电影', '音乐', '演唱会', '课程', '教程', '学习', '培训',
    // 介质 / 画质
    '蓝光', '原盘', '高清', '超清', 'bd', 'hd', 'remux', '4k', '1080p', '720p',
  ];

  /// 前缀式容器名（`新建文件夹 (2)`、`未命名文件夹 3` 这种带后缀的）。
  static const List<String> _containerPrefixes = [
    '来自分享', '我的分享', '新建文件夹', '未命名', '副本',
  ];

  /// 形态类容器名。
  ///
  /// 传进来的是**小写后的原串**（不是归一化串）—— 这些规则要靠 `_` `.` 空格
  /// 这类分隔符本身来判定「序号 + 介质名」。
  static final List<RegExp> _containerPatterns = [
    // `day01` / `Day18` / `day_01` / `day 3`
    RegExp(r'^day[\s_\-]*\d+$'),
    // `04_视频` / `3.视频` / `5.二期视频` / `02 音频`
    RegExp(r'^\d+[\s._\-]*(第?[一二三四五六七八九十\d]+[期季])?[\s]*'
        r'(视频|音频|课件|资料|素材|文档|图片|字幕)$'),
    // `01 基础篇` / `02 进阶篇` / `03 高级篇` / `04 扩展篇`
    RegExp(r'^\d+[\s._\-]*(基础|进阶|高级|扩展|实战|入门|提高|核心|选修)篇$'),
    // `第2章` / `第 12 节`
    RegExp(r'^第[\s]*\d+[\s]*(章|节|讲|课|期|篇|集|话)$'),
    // 季 —— **结构**不是名字。`/进击的巨人/第三季/` 里的末级目录名若被当成
    // 作品名，会得到一部叫「第三季」的作品，而且刮削会拿「第三季」去搜
    // （前缀档必然误配）。2026-10-03 加：候选链会把每一级非容器目录名都
    // 当作一个搜索词，这条漏了就是白花一次额度。
    RegExp(r'^第[\s]*[一二三四五六七八九十\d]{1,3}[\s]*季$'),
    // `S02` / `Season 1` / `season2` / `S 3`
    RegExp(r'^s(eason)?[\s._\-]*\d{1,2}$'),
    // 纯编号（`day02/1/` 这种里层目录）
    RegExp(r'^\d+$'),
    // 日期：`2026-10-02` / `2026.10.2`
    RegExp(r'^\d{4}[-_.]\d{1,2}[-_.]\d{1,2}$'),
    // 分辨率：`1080p` / `2160P` / `4k`
    RegExp(r'^\d{3,4}[pi]$'),
    RegExp(r'^[248]k$'),
  ];

  /// 这一段目录名是不是「容器」（栏目 / 整理态 / 序号 / 介质名）。
  ///
  /// 返回 `true` 表示它**不可能**是一个作品名，调用方应继续往上看。
  static bool isContainerSegment(String segment) {
    final raw = segment.trim();
    if (raw.isEmpty) return true;

    final lower = raw.toLowerCase();
    final n = _norm(lower);

    // 单个字符（`1`、`a`、`·`）不是名字。
    if (n.length < 2) return true;

    for (final p in _containerPatterns) {
      if (p.hasMatch(lower)) return true;
    }
    if (_containerWords.contains(n)) return true;
    for (final pre in _containerPrefixes) {
      if (n.startsWith(pre)) return true;
    }
    return false;
  }

  /// 这个目录应该用哪一级的名字当作品名。
  ///
  /// 从末级往上找第一个「像名字」的目录名；一路都是容器则返回 `null`
  /// （调用方退回逐文件解析 —— **不许硬凑一个名字**）。
  ///
  /// 返回值已经去掉书名号 / 括号 / 分隔符：它同时会被当作在线刮削的查询词，
  /// `姜松《家电维修视频教程》` 带着书名号去搜只会更难命中。
  static String? seriesTitleOf(String dirPath) {
    final names = ancestorNames(dirPath);
    return names.isEmpty ? null : names.first;
  }

  /// 这个目录路径上**每一级「像名字」的目录名**，从末级往上。
  ///
  /// 与 [seriesTitleOf] 是同一套判据的两个出口：那个只要第一级
  /// （「这个目录该用哪一级的名字当作品名」），这个要全部
  /// （「在线刮削还有哪些词可以试」）。
  ///
  /// ## 为什么做成两个方法而不是各写一遍循环
  ///
  /// 两处对「什么算容器」的理解一旦漂移，就会出现「归组用的是 A、
  /// 刮削去搜的是 B」—— 而这种不一致**只在刮不到的时候才暴露**，
  /// 排查时看到的现象是「目录名明明是对的，为什么不用它搜」。
  ///
  /// ## 调用方注意
  ///
  /// 返回的是**候选**，不是「都该发一次请求」。多一条就多一个搜索词，
  /// 而豆瓣匿名额度实测只有约 10 个（见 `ScrapeQuery.fallbacks` 的取舍）。
  static List<String> ancestorNames(String dirPath) {
    final segments = dirPath
        .split('/')
        .map((s) => s.trim())
        .where((s) => s.isNotEmpty)
        .toList();

    final out = <String>[];
    for (var i = segments.length - 1; i >= 0; i--) {
      if (isContainerSegment(segments[i])) continue;
      final cleaned = _clean(segments[i]);
      if (cleaned != null) out.add(cleaned);
    }
    return out;
  }

  /// 清掉书名号 / 括号 / 多余分隔符。
  static String? _clean(String segment) {
    var s = segment;
    // 书名号与各种括号：`姜松《家电维修视频教程》` → `姜松 家电维修视频教程`
    s = s.replaceAll(RegExp(r'[《》〈〉「」『』【】\[\]（）()]'), ' ');
    // `.` 与 `_` 是分隔符；`-` 保留（`Spider-Man`、`100026801` 里的连字符）
    s = s.replaceAll(RegExp(r'[._]+'), ' ');
    s = s.replaceAll(RegExp(r'^[\s\-–—]+'), '');
    s = s.replaceAll(RegExp(r'[\s\-–—]+$'), '');
    s = s.replaceAll(RegExp(r'\s{2,}'), ' ').trim();
    return s.isEmpty ? null : s;
  }
}
