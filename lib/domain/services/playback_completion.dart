/// 「播完了」到底是不是真的播完了。
///
/// ## 为什么需要它
///
/// 两个内核（mpv / mdk）的 `completed` 都是**内核说 EOF 就算播完**，它不保证
/// 这一集真的被看过了。实测踩到的一次（2026-10-04，夸克转码档 HLS）：
///
/// ```
/// open → 回报进度 @ 10s → 2.2 秒后 completed → 自动连播下一集
/// ```
///
/// 而「自动连播」会把当前这条流换成下一集 —— 于是用户在 60 秒内被推着
/// 「看」完了 5 部片，每一部都只有声音没有画面。最糟的地方不是跳，而是
/// **它把故障盖住了**：真正的报错（这个流只有一两秒）从来没机会露出来，
/// 用户只看到播放窗口自己在疯狂换片。
///
/// ## 判据：位置太短 + 从没出过画面 → 不算播完
///
/// 两条是**与**的关系，缺一条就放行：
///   - [sawVideo] = 这次播放中内核有没有真的报过视频尺寸。没有画面却「播完了」，
///     那一定是开流 / 解码 / 取链失败了 —— 绝不该当成看完；
///   - 但**只看它不行**：本应用也索引纯音频文件（`ScanPolicy.audioOnly`），
///     那种文件从头到尾都没有画面，却是**正常播完**。所以还要看位置 ——
///     位置足够长就说明用户确实在看，一律放行。
///
/// 所以规则是：位置过了 [minPlayed] 就信它；位置很短时，只有在**确实出过
/// 画面**的情况下才勉强信（那可能是个真的短视频）。
///
/// ## 代价（明确承认）
///
/// 一个真·2 秒的短视频会被误判成「没播完」，于是不自动连播。这个方向是
/// **故意选的**：不连播的代价是用户少看一次自动跳转，而误连播的代价是
/// 整个播放列表被一次静默故障扫一遍。本应用的片源是电影 / 剧集，
/// 短于 3 秒的条目实际上不存在。
library;

/// 「播完」的护栏。
abstract final class PlaybackCompletion {
  const PlaybackCompletion._();

  /// 位置低于这个值时，「播完」需要额外的证据（出过画面）。
  ///
  /// 3 秒不是算出来的，是从实测里取的：故障现场的位置是 1~2 秒，
  /// 而任何一集正常剧集的开场都远远超过它。留一点余量是为了别把
  /// 「用户拖到片尾最后 2 秒然后播完」也一起拦掉 —— 那种情况位置
  /// 是整个片长，根本不在这条路上。
  static const Duration minPlayed = Duration(seconds: 3);

  /// 转码档（HLS）短于这个位置就报播完 → **可疑，值得抓证据**。
  ///
  /// ⚠️ 这个阈值**不参与** [isRealEnd] 的判定，两者是刻意分开的：
  /// 护栏决定「要不要自动连播」，阈值决定「要不要抓诊断」。混成一个的话，
  /// 就会出现 2026-10-04 踩到的那种情形 —— 故障现场的位置（3~7 秒）刚好
  /// 高于 [minPlayed]，护栏放行，诊断也跟着一起不跑，最关键的证据永远拿不到。
  ///
  /// 取 30 秒是因为它只用于**转码档**：`media.m3u8` 是整部片的转码流，
  /// 正常一集绝不会 30 秒就完。原画（带签名的直链文件）不走这条判据。
  static const Duration suspiciousHlsPosition = Duration(seconds: 30);

  /// 该不该把这次 `completed` 当成「这一集真的看完了」。
  ///
  /// [position] 是内核报的播放头位置；[sawVideo] 是本次播放中内核有没有
  /// 报过非零的视频尺寸（**不是**「现在有没有画面」）。
  static bool isRealEnd({
    required Duration position,
    required bool sawVideo,
  }) {
    if (position >= minPlayed) return true;
    // 位置很短：只有在确实出过画面时才信它。
    return sawVideo && position > Duration.zero;
  }

  /// 被拦下时写进诊断日志 / 提示的那句话。
  ///
  /// 把三个量都带上是有意的：下一次报「怎么不自动连播了」时，第一件要
  /// 确认的就是「当时位置是多少、有没有画面」—— 少了任何一个都没法判断
  /// 是「护栏误伤」还是「流真的坏了」。
  static String describe({
    required Duration position,
    required Duration duration,
    required bool sawVideo,
  }) =>
      '这一集只播到 ${position.inSeconds}s 就报播完了'
      '（时长=${duration.inSeconds}s，${sawVideo ? '出过画面' : '全程没有画面'}）'
      '—— 判为播放异常，不自动连播';
}
