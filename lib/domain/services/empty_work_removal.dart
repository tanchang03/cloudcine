import '../entities/media_work.dart';

/// 一部**空壳作品**（名下一条文件记录都没有）的移除计划与文案。
///
/// ## 它替代的那句话
///
/// 2026-10-17 现场：用户在媒体库点《仙逆剧场版：弑仙之战》，得到的是一句
/// 「这部作品下没有可播放的文件」。这句话**不是谎话，但是个误导**：那两个
/// 电影文件好好地在库里、也在网盘上，只是被「目录锚点」判据归到了上一层
/// 目录的剧集《仙逆》名下（`DirectoryAnchorIndex` 只让 `kind == episode`
/// 的作品当锚点，而 `/来自：分享/仙逆/` 下恰好只有一部剧集）—— 于是这条
/// 作品行成了空壳，而 `listWorks` 照样把它列出来。
/// 用户照着那句话理解成「文件没了」，接着去找「从媒体库删除」的入口，
/// 而那个分支上从来没有这个入口。
///
/// ## 为什么必须把原因列出来
///
/// 「没有文件」只是**结果**。走到这一步的原因至少有两种，而用户该做的
/// 下一件事完全不同：
///
///   1. 文件被归到了别的作品名下 —— 该做的是「去那一部里找」，移除这条
///      空壳行不丢任何内容；
///   2. 网盘上的文件真的没了 —— 移除这条索引行正是他想要的。
///
/// 两种情况下「从媒体库移除」都是安全的（删的是本地索引，重新扫描可
/// 找回），所以这里只把两种可能摊开让用户自己判断，不替他选。
class EmptyWorkRemovalPlan {
  const EmptyWorkRemovalPlan({required this.work});

  final MediaWork work;

  String get title => work.title;

  /// 标题行。点名的就是用户刚才点的那一部 —— 空泛的「这部作品」会让他
  /// 怀疑自己是不是点错了卡片。
  String get headline => '媒体库里《$title》名下没有任何文件记录。';

  /// 两种可能的原因。
  ///
  /// 合成一句「可能已失效」也能读，但那样用户无从判断自己遇上的是哪一种，
  /// 而下一次他要么白移除一部还在用的作品，要么对着一个修不好的入口反复点。
  List<String> get reasons => const [
        '文件被归到了别的作品名下 —— 放在剧集目录里的电影、在剧集目录下'
            '新开一层的子目录，都会被归到那部剧集上面；',
        '网盘上的文件已经不在，而索引还是上一次扫描留下的。',
      ];

  /// **这条不能省，也不能改软**：用户对「移除」的预期是「文件也没了」，
  /// 而这里删的恰恰只是本地索引 —— 必须把它说成一件好事。
  String get keepFilesWarning =>
      '要从媒体库移除这部作品吗？只清掉这台设备上的索引，网盘上的文件'
      '原样保留 —— 之后「重新扫描」就能把它们找回来。';

  String get confirmLabel => '从媒体库移除';

  /// 放在最前的那个按钮：这是唯一没有副作用的选择。
  String get dismissLabel => '暂不移除';

  /// 结果提示（SnackBar）。
  ///
  /// [removedFiles] 是真正删掉的**文件行**数。空壳作品删掉的作品行不带
  /// 任何文件，那时提文件数只会让人以为漏删了东西 —— 所以为 0 时不说。
  String doneMessage({required int removedFiles}) {
    if (removedFiles <= 0) return '已移除《$title》，网盘文件未动。';
    final files = removedFiles == 1 ? '1 个文件' : '$removedFiles 个文件';
    return '已移除《$title》（$files），网盘文件未动。';
  }

  @override
  String toString() => 'EmptyWorkRemovalPlan($title)';
}
