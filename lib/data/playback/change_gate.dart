/// 「值没变就不发」的闸 —— 两个播放引擎共用。
///
/// ## 为什么需要它
///
/// 两个内核的事件源都是**轮询式回调**：mpv 那边是 media_kit 的
/// `addListener`（约 10 Hz），mdk 那边是我们自己开的 400 ms 轮询窗口。
/// 它们**每次都把全部字段报一遍**，不管值有没有变。
///
/// 不过闸的代价是实打实的：
///   - 订阅方（播放页）收到 `tracks` 就会重跑「自动选字幕」与「还原音轨」；
///   - 收到 `videoSize` / `position` 就会重建。
///
/// 实测踩过的坑：`activeAudioTrackId` 忘了过闸，于是每 400 ms 抛两次
/// 「值没变」的事件，音轨菜单跟着每拍重建。
///
/// ## ⚠️ 它用的是 `==`
///
/// 所以被比较的类型**必须实现值相等**（`Duration` / `String` / `num` / `bool`
/// 自带；自定义的值对象要自己写 `==`，比如 `EngineVideoSize`）。
/// 不实现的话每次都是引用不等，闸等于不存在 —— 而且**不会报错**，
/// 只会表现为「订阅方莫名其妙地频繁重建」。
///
/// 这也是为什么不把闸做成「深比较」：那要按类型分派，反而更脆。
///
/// ## 为什么两个引擎共用一份
///
/// 它是纯逻辑、与内核无关，而「什么时候算变了」这条规则在两个引擎之间
/// **必须一致** —— 各写一份的话，同一部片子走不同内核会出现不同的重建节奏，
/// 表现成「某些片源界面会闪」。两个文件各留一份 12 行的复制品正是这类
/// 漂移的温床。
class ChangeGate<T> {
  /// 「有没有发过」必须单独记一位，**不能**靠 `_last == null` 判断。
  ///
  /// 因为 `null` 是一个**合法的值**：`activeSubtitleTrackId` 的 `null` 表示
  /// 「没有字幕在显示」，`activeAudioTrackId` 的 `null` 表示「引擎还没定」。
  /// 只比 `_last == null` 的话，**首次上报 null 会被吞掉** ——
  /// 而这正是「打开一个没有内嵌字幕的片子，字幕菜单一直停在上一集的状态」
  /// 的成因。这个坑是写测试时被抓出来的，不是推出来的。
  bool _has = false;
  T? _last;

  /// 值变了吗。`true` 表示「该发」，调用方据此决定要不要 `add`。
  bool accept(T value) {
    if (_has && _last == value) return false;
    _has = true;
    _last = value;
    return true;
  }

  /// 换源时归零。
  ///
  /// **必须调**：新流的 duration / 轨道 id 与旧流无关，不归零的话
  /// 「新流的值恰好等于旧流」会被判成没变而不上报 —— 而那种巧合并不罕见
  /// （换集时两集时长相同、轨道号相同都会撞上），症状是「换集后音轨菜单
  /// 不刷新」，只在特定片源上复现。
  void reset() {
    _has = false;
    _last = null;
  }
}
